#!/usr/bin/env python3
"""build_playbook.py — regenerate docs/playbook.md: curated trading rules + live stats.

Sessions read docs/playbook.md (~3 KB) instead of the full lessons list / calibration.json.
The endday session regenerates it once a day. Read-only on the data files. Never runs git.
USAGE: python3 scripts/build_playbook.py [--data public/data] [--out docs/playbook.md]
"""
import argparse, collections, json, os, sys, datetime as dt
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paper_wallet as pw

RULES_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "playbook-rules.md")

def load_rules():
    with open(RULES_PATH) as fh:
        return "\n".join(l for l in fh.read().splitlines() if not l.startswith("<!--"))


def pct(a, b): return f"{(100*a/b):.0f}%" if b else "n/a"

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--data", default="public/data"); ap.add_argument("--out", default="docs/playbook.md")
    a = ap.parse_args()
    cal = json.load(open(os.path.join(a.data, "calibration.json")))
    port = json.load(open(os.path.join(a.data, "portfolio.json")))
    rows = [r for r in cal if r.get("price_at_report") and r.get("price_next_report")]
    def call(r): return max((("bull", r["bull_pct"]), ("range", r["range_pct"]), ("bear", r["bear_pct"])), key=lambda t: t[1])[0]
    def ok(r):
        m = r["price_next_report"] / r["price_at_report"] - 1; c = call(r)
        return (c == "bull" and m > 0.005) or (c == "bear" and m < -0.005) or (c == "range" and abs(m) <= 0.01)
    by = collections.defaultdict(lambda: [0, 0]); bys = collections.defaultdict(lambda: [0, 0]); moves = []
    for r in rows:
        by[call(r)][0] += ok(r); by[call(r)][1] += 1
        bys[r["session"]][0] += ok(r); bys[r["session"]][1] += 1
        moves.append(abs(r["price_next_report"] / r["price_at_report"] - 1))
    last30 = rows[-30:]; hit30 = sum(ok(r) for r in last30)
    h = port.get("history") or []
    trades = [x for x in h if x["action"] in ("TP", "STOPPED_OUT", "LIQUIDATED", "CLOSE", "FLIP")]
    opens = [x for x in h if x["action"] in ("OPEN_LONG", "OPEN_SHORT", "FLIP")]
    fut_share = sum(1 for x in h if (x.get("futures") or {}).get("side") not in (None, "flat")) / max(1, len(h))
    cnt = collections.Counter(x["action"] for x in h)
    s = port["latest"]; p0 = h[0]["markPrice"] if h else s["markPrice"]
    paid = float((port.get("expenses") or {}).get("totalPaidUsd") or 0)
    bh = float(port.get("initialCapitalUsd") or 100) * s["markPrice"] / p0 - paid
    lines = ["# BTC Paper Desk — Playbook", "",
             f"_Auto-generated by scripts/build_playbook.py on {dt.datetime.now(dt.timezone(dt.timedelta(hours=-5))).isoformat(timespec='minutes')}. Curated rules + live stats. Read this instead of the full lessons/calibration files._", "",
             load_rules().strip(), "", "## Live stats",
             "Call accuracy (dominant call vs next report; range = |move| <= 1%, bull/bear = move beyond 0.5%):",
             "| call | hit | n |", "|---|---|---|"]
    for c in ("range", "bull", "bear"):
        hh, n = by[c]; lines.append(f"| {c} | {pct(hh, n)} | {n} |")
    lines += ["", "By session: " + ", ".join(f"{k} {pct(v[0], v[1])} (n={v[1]})" for k, v in sorted(bys.items())),
              f"Last 30 graded reports: {pct(hit30, len(last30))}. Median move between reports: {100*sorted(moves)[len(moves)//2]:.2f}%." if moves else "",
              "", "Wallet:",
              f"- Futures open in {fut_share*100:.0f}% of snapshots; {len(opens)} opens; exits {dict(collections.Counter(x['action'] for x in trades))}.",
              f"- Spot churn: ADD {cnt['ADD']} / REDUCE {cnt['REDUCE']} / HOLD {cnt['HOLD']}.",
              f"- Net worth {s['netWorthUsd']} vs buy&hold {bh:.2f} (after {paid:.0f} USDT expenses) -> edge {s['netWorthUsd']-bh:+.2f} USDT.",
              "- Scoreboard (attributed PnL): " + ", ".join(f"{r['session']} {r['attributedPnlUsd']:+.2f}" for r in port.get("scoreboard", [])),
              "", "Goals now: " + json.dumps(pw.goals(port), separators=(",", ":")),
              "", "Last weekly digest: " + (lambda d: f"{d['weekStart']}..{d['weekEnd']} {d.get('title') or ''}: " + " | ".join(p["pattern"] for p in d["patterns"]) if d else "none")((port.get("lessonDigests") or [None])[-1]),
              "", "Archived lessons: public/data/lessons-archive.json (do not read in a session run)."]
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    open(a.out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {a.out} ({os.path.getsize(a.out)} bytes)")

if __name__ == "__main__":
    main()
